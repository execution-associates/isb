// Writes src/ea-ramps.css: ordered-dither (Bayer 8x8) ramps as SVG masks for
// the Execution Associates theme's CSS-only dithered fades (meter tails, the
// glow on a dialog's top edge, the sign-in panel's feathered edge). The same
// threshold matrix, strength and cell size the page's WebGL layer
// (lib/texture-gl.ts) uses, from DITHER in lib/texture.ts.
// Run: bun scripts/dither-ramps.ts
import { writeFileSync } from "node:fs";
import { DITHER } from "../src/lib/texture";

function bayer(n: number): number[][] {
  if (n === 2) return [[0, 2], [3, 1]];
  const b = bayer(n / 2);
  const m = b.length;
  const out: number[][] = Array.from({ length: n }, () => Array(n).fill(0));
  for (let y = 0; y < m; y++)
    for (let x = 0; x < m; x++) {
      out[y][x] = 4 * b[y][x];
      out[y][x + m] = 4 * b[y][x] + 2;
      out[y + m][x] = 4 * b[y][x] + 3;
      out[y + m][x + m] = 4 * b[y][x] + 1;
    }
  return out;
}
const B = bayer(8);
const thr = (x: number, y: number) => (B[y & 7][x & 7] + 0.5) / 64;
const { strength, cell } = DITHER;

/**
 * A ramp `px` long (opaque at 0, clear at the end), 8 cells across. Each cell's
 * alpha is the smooth fade pulled toward the Bayer on/off value by `strength`,
 * in 64 steps; cells of one alpha are drawn as runs in one path.
 */
function ramp(px: number, vertical: boolean): string {
  const cells = px / cell;
  const paths = new Map<number, string>();
  for (let across = 0; across < 8; across++) {
    let run = 0;
    let runA = -1;
    for (let i = 0; i <= cells; i++) {
      let a = 0;
      if (i < cells) {
        const s = 1 - (i + 0.5) / cells;
        const on = s > thr(vertical ? across : i, vertical ? i : across) ? 1 : 0;
        a = Math.round((s + strength * (on - s)) * 64);
      }
      if (i < cells && a === runA) continue;
      if (runA > 0) {
        const d = vertical ? `M${across} ${run}h1v${i - run}h-1z` : `M${run} ${across}h${i - run}v1h-${i - run}z`;
        paths.set(runA, (paths.get(runA) ?? "") + d);
      }
      run = i;
      runA = a;
    }
  }
  let body = "";
  for (const [a, d] of [...paths].toSorted(([x], [y]) => x - y)) {
    body += a === 64 ? `<path d='${d}'/>` : `<path fill-opacity='${+(a / 64).toFixed(4)}' d='${d}'/>`;
  }
  const w = vertical ? 8 : cells;
  const h = vertical ? cells : 8;
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='${w * cell}' height='${h * cell}' viewBox='0 0 ${w} ${h}' shape-rendering='crispEdges'>${body}</svg>`;
  return `url("data:image/svg+xml,${svg.replace(/</g, "%3C").replace(/>/g, "%3E").replace(/#/g, "%23")}")`;
}

const css = `/* Generated by scripts/dither-ramps.ts; do not edit. */
:root {
  --ea-ramp-tile: ${8 * cell}px; /* a ramp's width across its fade */
  --ea-ramp-x-s: ${ramp(48, false)}; /* 48px long */
  --ea-ramp-x-l: ${ramp(128, false)}; /* 128px long */
  --ea-ramp-y-s: ${ramp(48, true)}; /* 48px tall */
  --ea-ramp-y-l: ${ramp(128, true)}; /* 128px tall */
}
`;
writeFileSync(new URL("../src/ea-ramps.css", import.meta.url), css);
